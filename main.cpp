#include <iostream> // We include a standard library, namely the input output stream(iostream) -

// This is how we define a function 'main' which should return an integer
int main() {
    // Use character out(cout) which print one or more text on the screen

    std::cout << "Hello World!"; // This line is called a statement, it tells the OS what to do. We always terminate this with a semi colon.

    return 0; // The zero tells the OS that the program will terminate properly. Returning any non-zero number reports an error usually.
}